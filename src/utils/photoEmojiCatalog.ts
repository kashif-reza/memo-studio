interface QuickPhotoSpec {
  id: string;
  name: string;
  shortcode: string;
  photoUrl: string;
  vibeTag: string;
  defaultCaption: string;
  category: 'original' | 'new-solo' | 'split-sheet' | 'user-drop';
  mood: MoodVibeId;
  sourceSheetName?: string;
  faceShape: FaceShapeId;
  primaryColor: string;
  secondaryColor: string;
  outlineColor: string;
  eyes: EyeStyleId;
  brows: BrowStyleId;
  mouth: MouthStyleId;
  cheeks: CheekStyleId;
  accessory: AccessoryId;
  accessoryColor: string;
  effect: EffectId;
  effectColor: string;
  motionPreset: MotionPresetId;
  photoScale?: number;
  photoOffsetY?: number;
  photoMixMode?: PhotoMixMode;
  secondaryPhotoUrl?: string | null;
}

function buildPhotoItem(spec: QuickPhotoSpec): GivenPhotoItem {
  return {
    id: spec.id,
    name: spec.name,
    shortcode: spec.shortcode,
    photoUrl: spec.photoUrl,
    vibeTag: spec.vibeTag,
    defaultCaption: spec.defaultCaption,
    category: spec.category,
    mood: spec.mood,
    sourceSheetName: spec.sourceSheetName,
    matchingConfig: {
      id: spec.id,
      name: spec.name,
      shortcode: spec.shortcode,
      photoUrl: spec.photoUrl,
      secondaryPhotoUrl: spec.secondaryPhotoUrl ?? null,
      photoMixMode: spec.photoMixMode ?? 'cutout-solo',
      photoScale: spec.photoScale ?? 1.12,
      photoOffsetY: spec.photoOffsetY ?? 0,
      captionText: spec.defaultCaption,
      faceShape: spec.faceShape,
      primaryColor: spec.primaryColor,
      secondaryColor: spec.secondaryColor,
      outlineColor: spec.outlineColor,
      outlineWidth: 4,
      has3DShading: true,
      eyes: spec.eyes,
      eyeColor: '#0F172A',
      brows: spec.brows,
      mouth: spec.mouth,
      cheeks: spec.cheeks,
      cheekColor: '#FB7185',
      accessory: spec.accessory,
      accessoryColor: spec.accessoryColor,
      effect: spec.effect,
      effectColor: spec.effectColor,
      fineTune: { ...DEFAULT_FINE_TUNE },
      motionPreset: spec.motionPreset,
      motionSpeed: 1.1,
      motionIntensity: 1.15,
      easing: 'snappy-spring',
      layerMotion: { ...DEFAULT_LAYER_MOTION },
    },
  };
}

