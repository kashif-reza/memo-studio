/**
 * Pure calculation for slicing a multi-reaction sticker sheet image into a grid of solo reaction boxes.
 */
export function computeSheetGridSlices(
  imageWidth: number,
  imageHeight: number,
  rows: number,
  cols: number,
  paddingRatio = 0.04
): SheetSliceBox[] {
  const safeRows = Math.max(1, Math.min(6, Math.floor(rows)));
  const safeCols = Math.max(1, Math.min(6, Math.floor(cols)));
  const cellW = imageWidth / safeCols;
  const cellH = imageHeight / safeRows;
  const padX = cellW * paddingRatio;
  const padY = cellH * paddingRatio;

  const boxes: SheetSliceBox[] = [];
  let idx = 1;
  for (let r = 0; r < safeRows; r++) {
    for (let c = 0; c < safeCols; c++) {
      boxes.push({
        id: `slice-${r + 1}-${c + 1}`,
        x: Math.round(c * cellW + padX),
        y: Math.round(r * cellH + padY),
        width: Math.max(16, Math.round(cellW - padX * 2)),
        height: Math.max(16, Math.round(cellH - padY * 2)),
        label: `Reaction #${idx}`,
      });
      idx++;
    }
  }
  return boxes;
}

