/**
 * Generates a random combination mixing from the available realistic photos (including user-dropped
 * images and separated sheet stickers), vector accessories, particle effects, and motion physics.
 */
export function randomizePhotoCombo(
  seed?: number,
  customPool?: GivenPhotoItem[],
  moodFilter: MoodVibeId = 'all'
): {
  config: EmojiConfig;
  parentA: GivenPhotoItem;
  parentB: GivenPhotoItem;
} {
  let s = seed ?? Math.floor(Math.random() * 1000000);
  const nextRand = () => {
    s = (s * 1664525 + 1013904223) % 4294967296;
    return s / 4294967296;
  };
  const pick = <T,>(arr: T[]): T => arr[Math.floor(nextRand() * arr.length)];

  const basePool = customPool && customPool.length > 0 ? customPool : GIVEN_PHOTO_EMOJIS;
  const moodMatched =
    moodFilter === 'all'
      ? basePool
      : basePool.filter((item) => item.mood === moodFilter);
  const activePool = moodMatched.length >= 2 ? moodMatched : basePool;

  const parentA = pick(activePool);
  const remaining = activePool.filter((item) => item.id !== parentA.id);
  const parentB = pick(remaining.length > 0 ? remaining : activePool);

  const modes: PhotoMixMode[] = [
    'duo-collab',
    'vector-overlay',
    'cross-morph',
    'cutout-solo',
  ];
  const chosenMode = pick(modes);
  const baseMix = mixEmojiConfigs(parentA.matchingConfig, parentB.matchingConfig, chosenMode);

  const nonEmptyGear = ACCESSORY_STYLES.filter((a) => a.id !== 'none');
  const nonEmptyFx = EFFECT_STYLES.filter((e) => e.id !== 'none');

  const config: EmojiConfig = {
    ...baseMix,
    faceShape: pick(FACE_SHAPES).id,
    accessory: pick(nonEmptyGear).id,
    effect: pick(nonEmptyFx).id,
    motionPreset: pick(MOTION_PRESETS).id,
  };

  return { config, parentA, parentB };
}
